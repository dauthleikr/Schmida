  function markdownToHtml(value) {
    const inline = (line) => escapeHtml(line)
      .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noreferrer">$1</a>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      .replace(/_([^_]+)_/g, '<em>$1</em>');
    let html = '';
    let listOpen = false;
    String(value ?? '').split('\n').forEach((line) => {
      if (line.startsWith('- ')) {
        if (!listOpen) { html += '<ul>'; listOpen = true; }
        html += `<li>${inline(line.slice(2))}</li>`;
      } else {
        if (listOpen) { html += '</ul>'; listOpen = false; }
        html += `${inline(line)}<br>`;
      }
    });
    return listOpen ? `${html}</ul>` : html;
  }

  function htmlToMarkdown(node) {
    const convert = (item) => {
      if (item.nodeType === Node.TEXT_NODE) return item.nodeValue;
      if (item.nodeType !== Node.ELEMENT_NODE) return '';
      const content = [...item.childNodes].map(convert).join('');
      const tag = item.tagName.toLowerCase();
      if (tag === 'br') return '\n';
      if (tag === 'strong' || tag === 'b') return `**${content.trim()}**`;
      if (tag === 'em' || tag === 'i') return `_${content.trim()}_`;
      if (tag === 'a') return `[${content.trim()}](${item.getAttribute('href') || ''})`;
      if (tag === 'li') return `- ${content.trim()}\n`;
      if (tag === 'div' || tag === 'p') return `${content}\n`;
      return content;
    };
    return [...node.childNodes].map(convert).join('').replace(/\n{3,}/g, '\n\n').trim();
  }

