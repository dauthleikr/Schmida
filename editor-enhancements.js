(() => {
  const model = window.practiceContentModel;
  const editor = document.querySelector('#editor');
  const status = document.querySelector('#status');
  const draftKey = 'practice-content-draft-v3';
  const legacyDraftKeys = ['practice-content-draft-v2','practice-content-draft-v1'];
  let connectedFile;
  let previewTimer;
  let previewSectionIndex = null;

  const clone = model.clone;
  const escapeHtml = (value) => String(value ?? '').replace(/[&<>"']/g,(character) => ({
    '&':'&amp;',
    '<':'&lt;',
    '>':'&gt;',
    '"':'&quot;',
    "'":'&#39;'
  }[character]));
  const pathParts = (path) => path.split('.').map((part) => /^\d+$/.test(part) ? Number(part) : part);
  const getPath = (source,path) => pathParts(path).reduce((value,key) => value?.[key],source);
  const setPath = (source,path,value) => {
    const parts = pathParts(path);
    const last = parts.pop();
    const target = parts.reduce((object,key) => object[key],source);
    target[last] = value;
  };
  const contentSource = (draft) => `/* Generated by editor.html. Do not edit this file manually. */\nwindow.practiceContent = ${JSON.stringify(draft,null,2)};\n`;

  const readStoredDraft = () => {
    try {
      const current = localStorage.getItem(draftKey);
      if (current) return JSON.parse(current);
    } catch {}
    return window.practiceContent;
  };
  let data = model.normalize(readStoredDraft());

  const queuePreview = () => {
    if (!document.querySelector('#preview-modal').open) return;
    clearTimeout(previewTimer);
    previewTimer = setTimeout(refreshPreview,300);
  };
  const saveDraft = (message = 'Entwurf gespeichert') => {
    try {
      data = model.normalize(data);
      localStorage.setItem(draftKey,JSON.stringify(data));
      status.textContent = message;
      queuePreview();
    } catch {
      status.textContent = 'Entwurf konnte nicht gespeichert werden';
    }
  };

  const panelHeading = (title,description) => `<div class="panel-heading"><div><h2>${escapeHtml(title)}</h2><p>${escapeHtml(description)}</p></div></div>`;
  const toolbar = '<div class="toolbar" aria-label="Formatierung"><button type="button" data-format="bold" title="Fett" aria-label="Fett"><strong>B</strong></button><button type="button" data-format="italic" title="Kursiv" aria-label="Kursiv"><em>I</em></button><button type="button" data-format="link" title="Link einfügen" aria-label="Link einfügen">↗</button><button type="button" data-format="bullet" title="Aufzählung" aria-label="Aufzählung">•</button></div>';
  const fieldMarkup = (field,path,value,{ compact = false } = {}) => {
    const wide = compact || field.type === 'text' ? '' : ' grid-wide';
    if (field.type === 'rich') {
      return `<div class="field${wide}"><label for="${escapeHtml(path)}">${escapeHtml(field.label)}</label>${toolbar}<textarea id="${escapeHtml(path)}" data-path="${escapeHtml(path)}" rows="${field.editorRows || 4}">${escapeHtml(value)}</textarea></div>`;
    }
    if (field.type === 'select') {
      return `<div class="field${wide}"><label for="${escapeHtml(path)}">${escapeHtml(field.label)}</label><select id="${escapeHtml(path)}" data-path="${escapeHtml(path)}">${field.options.map(([key,label]) => `<option value="${escapeHtml(key)}" ${key === value ? 'selected' : ''}>${escapeHtml(label)}</option>`).join('')}</select></div>`;
    }
    if (field.type === 'range') {
      return `<div class="field${wide}"><label class="range-label" for="${escapeHtml(path)}"><span>${escapeHtml(field.label)}</span><output for="${escapeHtml(path)}">${escapeHtml(value)}%</output></label><input type="range" id="${escapeHtml(path)}" data-path="${escapeHtml(path)}" min="${field.min}" max="${field.max}" step="${field.step || 1}" value="${escapeHtml(value)}"><p class="help">${escapeHtml(field.help || '')}</p></div>`;
    }
    if (field.type === 'color') {
      return `<div class="field${wide}"><label for="${escapeHtml(path)}">${escapeHtml(field.label)}</label><input type="color" id="${escapeHtml(path)}" data-path="${escapeHtml(path)}" value="${escapeHtml(value)}"></div>`;
    }
    return `<div class="field${wide}"><label for="${escapeHtml(path)}">${escapeHtml(field.label)}</label><input id="${escapeHtml(path)}" data-path="${escapeHtml(path)}" value="${escapeHtml(value)}"></div>`;
  };

  const colorFields = [
    ['--wine-950','Hero und dunkle Bereiche'],
    ['--header-bg','Header'],
    ['--wine-650','Akzent'],
    ['--ribbon-hot','Wellenlinien'],
    ['--rose-100','Zartrosa'],
    ['--practice-bg','Warmgrau'],
    ['--paper','Papier']
  ];

  function renderGeneral() {
    const panel = document.querySelector('#general');
    const theme = model.themes[data.colorTheme] || model.themes.wine;
    const palette = { ...theme,...data.customColors };
    panel.innerHTML = `${panelHeading('Allgemein','Praxisname, Navigation und das übergreifende Farbsystem.')}
      <div class="grid">
        ${fieldMarkup({ label:'Praxisname',type:'text' },'practiceName',data.practiceName)}
        ${fieldMarkup({ label:'Name der Person',type:'text' },'practitionerName',data.practitionerName)}
        ${fieldMarkup({ label:'Navigation: Startseite',type:'text' },'navigation.home',data.navigation.home)}
        <div class="field grid-wide">
          <span class="field-label">Farbsystem</span>
          <div class="theme-options">
            ${Object.entries(model.themes).map(([key,item]) => `<label class="theme-option" style="--preview-deep:${item['--wine-950']};--preview-accent:${item['--wine-650']};--preview-ribbon:${item['--ribbon-hot']}"><input type="radio" name="theme" value="${key}" ${key === data.colorTheme ? 'checked' : ''}><span class="theme-swatch"></span><span class="theme-label">${escapeHtml(item.label)}</span></label>`).join('')}
          </div>
          <div class="color-controls">
            ${colorFields.map(([token,label]) => `<div class="color-control"><label>${escapeHtml(label)}</label><input type="color" data-global-color="${token}" value="${escapeHtml(palette[token])}"><input type="text" data-global-color-code="${token}" value="${escapeHtml(palette[token])}" spellcheck="false"></div>`).join('')}
          </div>
        </div>
      </div>`;
  }

  function renderHero() {
    const panel = document.querySelector('#hero-editor');
    const image = data.heroImage;
    panel.innerHTML = `${panelHeading('Startseite','Hero-Text und Bildgestaltung bleiben als fester Einstieg erhalten. Seitliche und mobile Bilder werden vollständig ohne Beschnitt dargestellt.')}
      <div class="grid">
        ${fieldMarkup({ label:'Überzeile',type:'text' },'hero.eyebrow',data.hero.eyebrow)}
        ${fieldMarkup({ label:'Titel',type:'rich',editorRows:3 },'hero.title',data.hero.title)}
        ${fieldMarkup({ label:'Titelgröße',type:'select',options:model.titleSizeOptions },'hero.titleSize',data.hero.titleSize)}
        ${fieldMarkup({ label:'Einleitung',type:'rich',editorRows:4 },'hero.sentence',data.hero.sentence)}
        ${fieldMarkup({ label:'Kontakt-Button',type:'text' },'hero.contactButton',data.hero.contactButton)}
        <div class="hero-settings grid-wide">
          <div class="grid">
            ${fieldMarkup({ label:'Bilddatei',type:'text' },'heroImage.src',image.src)}
            ${fieldMarkup({ label:'Alternativtext',type:'text' },'heroImage.alt',image.alt)}
            ${fieldMarkup({ label:'Bildformat Desktop',type:'select',options:[['portrait','Seitliches Porträt'],['landscape','Breite Fotofläche'],['background','Vollflächiger Hintergrund']] },'heroImage.layout',image.layout)}
            ${fieldMarkup({ label:'Bildwirkung',type:'select',options:[['duotone','Weiches Duoton'],['natural','Natürlich'],['mono','Monochrom'],['warm','Warm und weich']] },'heroImage.blend',image.blend)}
            ${fieldMarkup({ label:'Bild auf Mobilgeräten',type:'select',options:[['portrait','Anzeigen'],['hidden','Ausblenden']] },'heroImage.mobileLayout',image.mobileLayout === 'hidden' ? 'hidden' : 'portrait')}
            ${fieldMarkup({ label:'Textüberlagerung',type:'select',options:[['soft','Sanft'],['strong','Stark'],['none','Keine']] },'heroImage.overlay',image.overlay)}
            ${fieldMarkup({ label:'Blendbreite Desktop',type:'range',min:5,max:80,step:1,help:'Wie weit die Überblendung von links in das Bild reicht.' },'heroImage.blendWidthDesktop',image.blendWidthDesktop)}
            ${fieldMarkup({ label:'Blendbreite Mobil',type:'range',min:5,max:80,step:1,help:'Wie weit die Überblendung von oben in das Bild reicht.' },'heroImage.blendWidthMobile',image.blendWidthMobile)}
          </div>
        </div>
      </div>`;
  }

  function collectionMarkup(sectionIndex,field) {
    const path = `sections.${sectionIndex}.content.${field.key}`;
    const items = getPath(data,path) || [];
    const template = model.layouts[data.sections[sectionIndex].layout].defaults[field.key]?.[0] || {};
    return `<div class="collection">
      <div class="collection-head"><div><span class="field-label">${escapeHtml(field.label)}</span><span> · ${items.length}${field.max ? ` von ${field.max}` : ''}</span></div><button class="button" type="button" data-collection-action="add" data-section-index="${sectionIndex}" data-collection-key="${field.key}" ${items.length >= (field.max ?? Infinity) ? 'disabled' : ''}>${escapeHtml(field.addLabel || 'Eintrag hinzufügen')}</button></div>
      <div class="collection-list">
        ${items.map((item,itemIndex) => `<div class="collection-item" data-collection-item="${itemIndex}"><div class="collection-fields" style="--item-columns:${Math.min(3,field.itemFields.length)}">${field.itemFields.map((itemField) => fieldMarkup(itemField,`${path}.${itemIndex}.${itemField.key}`,item[itemField.key],{ compact:true })).join('')}</div><button class="icon-button" type="button" data-collection-action="remove" data-section-index="${sectionIndex}" data-collection-key="${field.key}" data-item-index="${itemIndex}" aria-label="Eintrag entfernen" ${items.length <= (field.min || 0) ? 'disabled' : ''}>&times;</button></div>`).join('')}
      </div>
      <template data-collection-template="${field.key}">${escapeHtml(JSON.stringify(template))}</template>
    </div>`;
  }

  function renderSectionCard(section,index) {
    const definition = model.layouts[section.layout];
    const colorOptions = model.sectionColors.map((color) => `<option value="${color.key}" ${section.background === color.key ? 'selected' : ''}>${escapeHtml(color.label)}</option>`).join('');
    return `<article class="section-editor" data-section-index="${index}" data-section-id="${escapeHtml(section.id)}">
      <header class="section-editor-head">
        <div><h3 class="section-title">${escapeHtml(section.internalName)}</h3><p class="section-meta">Bereich ${index + 1} · ${escapeHtml(definition.label)} · ${section.navigationLabel ? `Navigation: ${escapeHtml(section.navigationLabel)}` : 'nicht in der Navigation'}</p></div>
        <div class="section-actions">
          <button class="section-preview-button" type="button" data-section-preview="mobile" aria-label="Mobilvorschau für ${escapeHtml(section.internalName)}">Mobil</button>
          <button class="section-preview-button" type="button" data-section-preview="desktop" aria-label="Desktopvorschau für ${escapeHtml(section.internalName)}">Desktop</button>
          <button class="icon-button" type="button" data-section-action="up" aria-label="Nach oben" ${index === 0 ? 'disabled' : ''}>↑</button>
          <button class="icon-button" type="button" data-section-action="down" aria-label="Nach unten" ${index === data.sections.length - 1 ? 'disabled' : ''}>↓</button>
          <button class="icon-button" type="button" data-section-action="remove" aria-label="Bereich entfernen">&times;</button>
        </div>
      </header>
      <div class="section-editor-body">
        <div class="section-settings">
          <div class="field"><label>Interner Name</label><input data-path="sections.${index}.internalName" value="${escapeHtml(section.internalName)}"><p class="help">Nur im Editor sichtbar.</p></div>
          <div class="field"><label>Layout</label><select data-section-layout>${Object.entries(model.layouts).map(([key,item]) => `<option value="${key}" ${section.layout === key ? 'selected' : ''}>${escapeHtml(item.label)}</option>`).join('')}</select></div>
          <div class="field"><label>Navigation</label><input data-path="sections.${index}.navigationLabel" value="${escapeHtml(section.navigationLabel)}"><p class="help">Leer lassen, um den Bereich nicht im Menü zu zeigen.</p></div>
          <div class="field"><label>Hintergrund</label><select data-section-background>${colorOptions}</select>${section.background === 'custom' ? `<div class="background-custom"><input type="color" data-section-custom-color value="${escapeHtml(section.customBackground)}"><input data-section-custom-code value="${escapeHtml(section.customBackground)}" spellcheck="false"></div>` : ''}</div>
          ${(definition.appearanceFields || []).filter((field) => !field.visibleWhen || field.visibleWhen.values.includes(section.appearance[field.visibleWhen.key])).map((field) => fieldMarkup(field,`sections.${index}.appearance.${field.key}`,section.appearance[field.key],{ compact:true })).join('')}
          <p class="layout-description">${escapeHtml(definition.description)}</p>
        </div>
        <div class="section-fields">
          ${definition.fields.map((field) => field.type === 'collection' ? collectionMarkup(index,field) : fieldMarkup(field,`sections.${index}.content.${field.key}`,section.content[field.key])).join('')}
        </div>
      </div>
    </article>`;
  }

  function renderSections() {
    const panel = document.querySelector('#sections-editor');
    panel.innerHTML = `${panelHeading('Seitenbereiche','Bereiche können frei hinzugefügt, entfernt, sortiert und mit jedem registrierten Layout gestaltet werden.')}
      <div class="section-stack">${data.sections.length ? data.sections.map(renderSectionCard).join('') : '<div class="empty-sections">Noch keine Seitenbereiche. Hero und Footer bleiben bestehen.</div>'}</div>
      <div class="add-section">
        <div class="field"><label for="new-layout">Layout für neuen Bereich</label><select id="new-layout">${Object.entries(model.layouts).map(([key,item]) => `<option value="${key}">${escapeHtml(item.label)} – ${escapeHtml(item.description)}</option>`).join('')}</select></div>
        <button class="button primary" type="button" id="add-section">Bereich hinzufügen</button>
      </div>`;
  }

  function renderFooter() {
    const panel = document.querySelector('#footer-editor');
    panel.innerHTML = `${panelHeading('Footer','Der kompakte dunkle Abschluss bleibt fest bestehen.')}<div class="grid">${fieldMarkup({ label:'Copyright-Zeile',type:'text' },'footer.copyright',data.footer.copyright)}</div>`;
  }

  function renderAll() {
    renderGeneral();
    renderHero();
    renderSections();
    renderFooter();
  }

  const refreshPreview = () => {
    try {
      const normalized = model.normalize(data);
      const previewContent = previewSectionIndex === null
        ? normalized
        : { ...normalized,sections:[normalized.sections[previewSectionIndex]] };
      sessionStorage.setItem('practice-preview-content',JSON.stringify(previewContent));
      const isolated = previewSectionIndex === null ? '' : '&sectionPreview=1';
      document.querySelector('#preview-frame').src = `index.html?preview=1${isolated}&updated=${Date.now()}`;
    } catch {
      status.textContent = 'Vorschau konnte nicht aktualisiert werden';
    }
  };

  editor.addEventListener('input',(event) => {
    const path = event.target.dataset.path;
    if (path) {
      setPath(data,path,event.target.value);
      if (/^sections\.\d+\.internalName$/.test(path)) {
        const card = event.target.closest('[data-section-index]');
        const index = Number(card.dataset.sectionIndex);
        card.querySelector('.section-title').textContent = event.target.value.trim() || model.layouts[data.sections[index].layout].label;
      }
      const output = event.target.parentElement.querySelector('output');
      if (output) output.value = `${event.target.value}%`;
      saveDraft();
      if (path.endsWith('.appearance.listStyle')) renderSections();
      return;
    }
    const token = event.target.dataset.globalColor || event.target.dataset.globalColorCode;
    if (token) {
      const value = event.target.value.trim();
      if (!/^#[0-9a-f]{6}$/i.test(value)) {
        status.textContent = 'Bitte eine sechsstellige Hex-Farbe eingeben';
        return;
      }
      data.customColors[token] = value;
      const pairSelector = event.target.dataset.globalColor ? `[data-global-color-code="${token}"]` : `[data-global-color="${token}"]`;
      document.querySelector(pairSelector).value = value;
      saveDraft();
      return;
    }
    const card = event.target.closest('[data-section-index]');
    if (card && event.target.matches('[data-section-custom-color],[data-section-custom-code]')) {
      const value = event.target.value.trim();
      if (!/^#[0-9a-f]{6}$/i.test(value)) {
        status.textContent = 'Bitte eine sechsstellige Hex-Farbe eingeben';
        return;
      }
      const index = Number(card.dataset.sectionIndex);
      data.sections[index].customBackground = value;
      const pair = card.querySelector(event.target.matches('[data-section-custom-color]') ? '[data-section-custom-code]' : '[data-section-custom-color]');
      pair.value = value;
      saveDraft();
    }
  });

  editor.addEventListener('change',(event) => {
    if (event.target.name === 'theme') {
      data.colorTheme = event.target.value;
      data.customColors = {};
      saveDraft();
      renderGeneral();
      return;
    }
    const card = event.target.closest('[data-section-index]');
    if (!card) return;
    const index = Number(card.dataset.sectionIndex);
    if (event.target.matches('[data-section-background]')) {
      data.sections[index].background = event.target.value;
      saveDraft();
      renderSections();
      return;
    }
    if (event.target.matches('[data-section-layout]')) {
      const oldSection = data.sections[index];
      const replacement = model.createSection(event.target.value,oldSection.id);
      if (oldSection.internalName !== model.layouts[oldSection.layout].label) replacement.internalName = oldSection.internalName;
      replacement.navigationLabel = oldSection.navigationLabel;
      replacement.background = oldSection.background;
      replacement.customBackground = oldSection.customBackground;
      replacement.appearance = { ...replacement.appearance,...oldSection.appearance };
      Object.keys(replacement.content).forEach((key) => {
        if (typeof replacement.content[key] === 'string' && typeof oldSection.content[key] === 'string') replacement.content[key] = oldSection.content[key];
      });
      data.sections[index] = replacement;
      saveDraft();
      renderSections();
    }
  });

  editor.addEventListener('mousedown',(event) => {
    if (event.target.closest('[data-format]')) event.preventDefault();
  });

  editor.addEventListener('click',(event) => {
    const format = event.target.closest('[data-format]')?.dataset.format;
    if (format) {
      const textarea = event.target.closest('.field')?.querySelector('textarea');
      if (!textarea) return;
      const start = textarea.selectionStart;
      const end = textarea.selectionEnd;
      const selection = textarea.value.slice(start,end) || 'Text';
      let replacement = selection;
      if (format === 'bold') replacement = `**${selection}**`;
      if (format === 'italic') replacement = `_${selection}_`;
      if (format === 'bullet') replacement = selection.split('\n').map((line) => `- ${line.replace(/^-\s*/, '')}`).join('\n');
      if (format === 'link') {
        const url = prompt('Webadresse eingeben (https://...)','https://');
        if (!url) return;
        replacement = `[${selection}](${url})`;
      }
      textarea.value = `${textarea.value.slice(0,start)}${replacement}${textarea.value.slice(end)}`;
      textarea.focus();
      textarea.setSelectionRange(start,start + replacement.length);
      textarea.dispatchEvent(new Event('input',{ bubbles:true }));
      return;
    }

    const sectionAction = event.target.closest('[data-section-action]')?.dataset.sectionAction;
    if (sectionAction) {
      const index = Number(event.target.closest('[data-section-index]').dataset.sectionIndex);
      if (sectionAction === 'remove') {
        if (!confirm('Diesen Seitenbereich wirklich entfernen?')) return;
        data.sections.splice(index,1);
      } else {
        const nextIndex = sectionAction === 'up' ? index - 1 : index + 1;
        if (nextIndex < 0 || nextIndex >= data.sections.length) return;
        [data.sections[index],data.sections[nextIndex]] = [data.sections[nextIndex],data.sections[index]];
      }
      saveDraft();
      renderSections();
      return;
    }

    const sectionPreview = event.target.closest('[data-section-preview]')?.dataset.sectionPreview;
    if (sectionPreview) {
      const index = Number(event.target.closest('[data-section-index]').dataset.sectionIndex);
      const dialog = document.querySelector('#preview-modal');
      previewSectionIndex = index;
      dialog.dataset.viewport = sectionPreview;
      dialog.querySelector('.preview-head h2').textContent = `${data.sections[index].internalName} · ${sectionPreview === 'mobile' ? 'Mobil' : 'Desktop'}`;
      dialog.showModal();
      refreshPreview();
      return;
    }

    const collectionAction = event.target.closest('[data-collection-action]')?.dataset.collectionAction;
    if (collectionAction) {
      const button = event.target.closest('[data-collection-action]');
      const sectionIndex = Number(button.dataset.sectionIndex);
      const key = button.dataset.collectionKey;
      const definition = model.layouts[data.sections[sectionIndex].layout];
      const field = definition.fields.find((candidate) => candidate.key === key);
      const items = data.sections[sectionIndex].content[key];
      if (collectionAction === 'add' && items.length < (field.max ?? Infinity)) {
        items.push(clone(definition.defaults[key]?.[0] || Object.fromEntries(field.itemFields.map((itemField) => [itemField.key,'']))));
      }
      if (collectionAction === 'remove' && items.length > (field.min || 0)) items.splice(Number(button.dataset.itemIndex),1);
      saveDraft();
      renderSections();
      return;
    }

    if (event.target.closest('#add-section')) {
      const layout = document.querySelector('#new-layout').value;
      const base = `${layout}-${Date.now().toString(36)}`;
      const ids = new Set(data.sections.map((section) => section.id));
      let id = base;
      let suffix = 2;
      while (ids.has(id)) id = `${base}-${suffix++}`;
      data.sections.push(model.createSection(layout,id));
      saveDraft();
      renderSections();
    }
  });

  const database = () => new Promise((resolve,reject) => {
    const request = indexedDB.open('practice-editor-files',1);
    request.onupgradeneeded = () => request.result.createObjectStore('handles');
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
  const storeHandle = async (handle) => {
    const db = await database();
    const transaction = db.transaction('handles','readwrite');
    transaction.objectStore('handles').put(handle,'content');
    return new Promise((resolve,reject) => {
      transaction.oncomplete = resolve;
      transaction.onerror = () => reject(transaction.error);
    });
  };
  const loadHandle = async () => {
    const db = await database();
    const transaction = db.transaction('handles');
    const request = transaction.objectStore('handles').get('content');
    return new Promise((resolve,reject) => {
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  };
  const parseContentFile = (source) => {
    const match = source.match(/window\.practiceContent\s*=\s*([\s\S]*?);\s*$/);
    if (!match) throw new Error('Practice content not found');
    return Function(`"use strict";return (${match[1]});`)();
  };
  async function activateContentFile(handle) {
    const source = await (await handle.getFile()).text();
    data = model.normalize(parseContentFile(source));
    connectedFile = handle;
    localStorage.setItem(draftKey,JSON.stringify(data));
    await storeHandle(handle);
    renderAll();
    status.textContent = 'content.js verbunden';
  }
  async function connectContentFile() {
    if (!window.showOpenFilePicker) return;
    try {
      const [handle] = await window.showOpenFilePicker({ types:[{ description:'Website content',accept:{ 'text/javascript':['.js'] } }],multiple:false });
      await activateContentFile(handle);
    } catch (error) {
      if (error.name !== 'AbortError') status.textContent = 'content.js konnte nicht verbunden werden';
    }
  }
  async function saveContentFile() {
    try {
      if (!connectedFile) {
        await connectContentFile();
        if (!connectedFile) return;
      }
      const state = await connectedFile.queryPermission({ mode:'readwrite' });
      const permission = state === 'granted' ? state : await connectedFile.requestPermission({ mode:'readwrite' });
      if (permission !== 'granted') throw new Error('Permission denied');
      const writable = await connectedFile.createWritable();
      await writable.write(contentSource(model.normalize(data)));
      await writable.close();
      status.textContent = 'content.js gespeichert';
    } catch {
      status.textContent = 'content.js konnte nicht gespeichert werden';
    }
  }
  const download = () => {
    const source = contentSource(model.normalize(data));
    const url = URL.createObjectURL(new Blob([source],{ type:'text/javascript' }));
    const link = document.createElement('a');
    link.href = url;
    link.download = 'content.js';
    link.click();
    URL.revokeObjectURL(url);
    status.textContent = 'content.js heruntergeladen';
  };

  document.querySelector('#connect-content').addEventListener('click',connectContentFile);
  document.querySelector('#save-content-direct').addEventListener('click',saveContentFile);
  document.querySelector('#download').addEventListener('click',download);
  document.querySelector('#download-bottom').addEventListener('click',download);
  document.querySelectorAll('[data-preview-viewport]').forEach((button) => button.addEventListener('click',() => {
    const dialog = document.querySelector('#preview-modal');
    const viewport = button.dataset.previewViewport;
    previewSectionIndex = null;
    dialog.dataset.viewport = viewport;
    dialog.querySelector('.preview-head h2').textContent = viewport === 'mobile' ? 'Vorschau Mobil' : 'Vorschau Desktop';
    dialog.showModal();
    refreshPreview();
  }));
  document.querySelector('#close-preview').addEventListener('click',() => document.querySelector('#preview-modal').close());
  document.querySelector('#reset').addEventListener('click',() => {
    if (!confirm('Entwurf wirklich zurücksetzen?')) return;
    localStorage.removeItem(draftKey);
    legacyDraftKeys.forEach((key) => localStorage.removeItem(key));
    data = model.normalize(window.practiceContent);
    renderAll();
    status.textContent = 'Entwurf zurückgesetzt';
  });

  if (!window.showOpenFilePicker) {
    document.querySelector('#connect-content').hidden = true;
    document.querySelector('#save-content-direct').hidden = true;
  } else {
    loadHandle().then((handle) => {
      if (handle) {
        connectedFile = handle;
        status.textContent = 'content.js verbunden';
      }
    }).catch(() => {});
  }
  document.addEventListener('dragover',(event) => event.preventDefault());
  document.addEventListener('drop',async (event) => {
    event.preventDefault();
    const item = event.dataTransfer.items?.[0];
    if (!item?.getAsFileSystemHandle) return;
    const handle = await item.getAsFileSystemHandle();
    if (handle?.kind === 'file' && handle.name === 'content.js') await activateContentFile(handle);
  });

  renderAll();
  saveDraft('Entwurf bereit');
})();
